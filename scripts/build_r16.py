# the collections' register: each product's own cloth as a small pinked cut (key, kind -> tile^line)
from craft_draw import cfg_of as _cfg_of, tile_name as _tile_name, SYS as _SYS
from lp_data import CLOTH as _CLOTH, CRAFT as _CRAFT2
def _main_cloth(key, kind):
    c = _cfg_of(key)
    if kind == 'boxspring' or key.startswith('base'):
        return c['base']
    if kind == 'topper' or key.startswith('topper'):
        return c['topper']
    for part in ('topper', 'base', 'mattress'):
        if c[part]['tex'] in ('paisley', 'damask', 'boucle'):
            return c[part]
    return c['mattress']
_ln = ["{%- comment -%} A product's own cloth, for the collections' register: its tile and its line (key, kind). Generated by bin/build_r16.py from bin/craft_draw.py and bin/lp_data.py. {%- endcomment -%}",
       "{%- if kind == 'system' or kind == 'mattress' or kind == 'topper' or kind == 'boxspring' -%}", "{%- case key -%}"]
for _k in sorted(set(list(_SYS.keys()) + [k for k in _CRAFT2 if k.startswith('base')])):
    _p = _main_cloth(_k, '')
    _tn = _tile_name(_p)
    assert os.path.exists(THEME + '/assets/' + _tn), _tn
    _line = _CLOTH.get(_k, {}).get('cover', '')
    _ln.append("{%%- when '%s' -%%}%s^%s" % (_k, _tn, _line.replace('^', ' ')))
_ln += ["{%- endcase -%}", "{%- endif -%}"]
open(THEME + '/snippets/ms-cloth-swatch.liquid', 'w').write('\n'.join(_ln) + '\n')
