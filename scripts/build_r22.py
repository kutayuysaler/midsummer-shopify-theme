# Round 22, run at the end of bin/build_more.py in its scope (THEME, SP, tpl_load, tpl_save...), after
# Round 21. Every step is an exact replacement or a guarded write, so a second build changes nothing.

_r22_n = 0


def _r22_sub(path, pairs):
    """Replace each (old, new) in the file at path; a pair already applied is skipped."""
    global _r22_n
    _t = open(path, encoding='utf-8').read()
    _u = _t
    for _a, _b in pairs:
        if _a in _u:
            _u = _u.replace(_a, _b)
    if _u != _t:
        open(path, 'w', encoding='utf-8').write(_u)
        _r22_n += 1


def _r22_write(path, text):
    global _r22_n
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        open(path, 'w', encoding='utf-8').write(text)
        _r22_n += 1


