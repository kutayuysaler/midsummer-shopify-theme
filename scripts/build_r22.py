# ── A product photographed on a white studio ground showed as a white sheet on the house's paper.
#    Such a photograph (its edge white all round) is laid into the ground it sits on, as a print is
#    on paper: the white takes the paper's colour, the product keeps its own. Photographs taken in a
#    room are left as they are. Product photographs only: the gallery and its thumbnails, the
#    collection cards, the related products, the comparison, the shop's own cards and cart.
_r22_write(THEME + '/snippets/ms-on-white.liquid', '''{%- comment -%}
  A product photographed on a white studio ground is laid into the paper it sits on (multiply), so
  its white takes the page's colour instead of showing as a white sheet. Found by the photograph's
  own edge, white all round; photographs taken in a room are untouched. Generated by bin/build_r22.py.
{%- endcomment -%}
<style>
  .ms-pm__slide { background: inherit; }
  img.ms-on-white { mix-blend-mode: multiply; }
</style>
<script>
  (function () {
    var SEL = '.ms-pm__slide img, .ms-pm__thumb img, .ms-rel__img img, .ms-card__img img, .ms-cmp__img img, .card-gallery img, .cart-items img, .cart-drawer img, .predictive-search img';
    var cv = null;
    // the photograph's edge, read small: nearly all of it white and without colour
    function white(img) {
      try {
        var n = 20; cv = cv || document.createElement('canvas'); cv.width = n; cv.height = n;
        var x = cv.getContext('2d', { willReadFrequently: true }); x.clearRect(0, 0, n, n); x.drawImage(img, 0, 0, n, n);
        var d = x.getImageData(0, 0, n, n).data, all = 0, ok = 0;
        for (var i = 0; i < n * n; i++) {
          var px = i % n, py = (i / n) | 0;
          if (px > 1 && px < n - 2 && py > 1 && py < n - 2) continue;
          var r = d[i * 4], g = d[i * 4 + 1], b = d[i * 4 + 2], a = d[i * 4 + 3];
          all++; if (a > 200 && Math.min(r, g, b) > 234 && Math.max(r, g, b) - Math.min(r, g, b) < 14) ok++;
        }
        return all && ok / all > 0.86;
      } catch (e) { return false; }
    }
    function mark(img) {
      if (img.dataset.msWhite) return;
      var go = function () { img.dataset.msWhite = '1'; if (white(img)) img.classList.add('ms-on-white'); };
      if (img.complete && img.naturalWidth) go(); else img.addEventListener('load', go, { once: true });
    }
    function scan(root) { if (root.matches && root.matches(SEL)) mark(root); if (root.querySelectorAll) root.querySelectorAll(SEL).forEach(mark); }
    function start() {
      scan(document);
      if ('MutationObserver' in window) new MutationObserver(function (ms) { ms.forEach(function (m) { m.addedNodes.forEach(function (nd) { if (nd.nodeType === 1) scan(nd); }); }); }).observe(document.body, { childList: true, subtree: true });
    }
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
  })();
</script>
''')
